#!/usr/bin/env python3
"""Add a finished run to ``samples/runs/`` (SHI-R1-03, FR-12.8, J2, J8, C-09). Owner: WS3.

The sandbox is wiped after the event, so the runs a demo needs must live in git. This copies one
finished run folder into ``samples/runs/<run_id>/`` and keeps ``samples/README.md`` current.

It refuses, with a message and without copying anything, when:

* the run is not finished or its trace is incomplete (no ``run_end``, a cut-off line);
* any file contains something that looks like a secret (the same patterns the tracer redacts, so
  a hit means a leak got past redaction). The message names the file and line, never the value;
* ``samples/runs/<run_id>`` already exists (samples are immutable; pick a new run).

Blobs over ``--max-blob-bytes`` (default 1 MB) are copied truncated, with a
``blobs/<name>.truncated.json`` sidecar holding ``truncated: true`` and the original size and hash.
The full copy belongs in S3. Finally it checks the copy can be replayed without any model: the
trace reads back complete, and the deterministic summary cites real events.

Usage::

    python scripts/add_sample.py --run runs/<run_id> --demonstrates "clean T1 run, Kern County"
    python scripts/add_sample.py --reindex          # only rebuild samples/README.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path
from typing import Any

from claysandbox.contracts.store import TERMINAL_STATES
from claysandbox.store.reader import read_trace
from claysandbox.summary.deterministic import DeterministicSummarizer
from claysandbox.tracing.redact import redact_text

MAX_BLOB_BYTES = 1_000_000
SIDECAR = "sample.json"
README_HEADER = (
    "# Sample runs\n\n"
    "Finished runs committed so the demo and the offline tests work after the sandbox is wiped\n"
    "(C-09). Replay any of them with no AWS access. Folders are immutable: add a new run, never\n"
    "edit one. This index is generated by `scripts/add_sample.py`; do not edit it by hand.\n\n"
)


class SampleError(Exception):
    """The run cannot be added; the message says why."""


def _is_leftover(path: Path) -> bool:
    return path.name.startswith(".") or ".tmp" in path.suffix


def check_finished(run_dir: Path) -> dict[str, Any]:
    for name in ("manifest.json", "trace.jsonl", "status.json"):
        if not (run_dir / name).exists():
            raise SampleError(f"{run_dir} has no {name}")
    state = json.loads((run_dir / "status.json").read_text()).get("state")
    if state not in TERMINAL_STATES:
        raise SampleError(f"{run_dir.name} is not finished (state: {state})")
    trace = read_trace(run_dir)
    if trace.incomplete:
        raise SampleError(f"{run_dir.name} has an incomplete trace (no run_end or a cut-off line)")
    return json.loads((run_dir / "manifest.json").read_text())


def scan_for_secrets(run_dir: Path) -> list[str]:
    """``file:line`` of every line the redactor would change. Never returns the secret itself."""
    hits: list[str] = []
    for path in sorted(p for p in run_dir.rglob("*") if p.is_file() and not _is_leftover(p)):
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue  # binary payload
        for n, line in enumerate(text.splitlines(), 1):
            if redact_text(line, env_secrets=[]) != line:
                hits.append(f"{path.relative_to(run_dir).as_posix()}:{n}")
    return hits


def copy_run(src: Path, dest: Path, max_blob_bytes: int) -> list[str]:
    """Copy the folder; truncate oversized blobs. Returns the truncated blob names."""
    truncated: list[str] = []
    for path in sorted(p for p in src.rglob("*") if p.is_file() and not _is_leftover(p)):
        rel = path.relative_to(src)
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if rel.parts[0] == "blobs" and path.stat().st_size > max_blob_bytes:
            raw = path.read_bytes()
            target.write_bytes(raw[:max_blob_bytes])
            target.with_name(target.name + ".truncated.json").write_text(
                json.dumps(
                    {
                        "truncated": True,
                        "original_bytes": len(raw),
                        "original_sha256": hashlib.sha256(raw).hexdigest(),
                        "kept_bytes": max_blob_bytes,
                    },
                    indent=2,
                )
                + "\n"
            )
            truncated.append(rel.as_posix())
        else:
            shutil.copy2(path, target)
    return truncated


def check_replayable(run_dir: Path) -> None:
    """The copy must read back complete and summarise offline with real citations."""
    trace = read_trace(run_dir)
    if trace.incomplete or not trace.events:
        raise SampleError("the copied trace does not read back complete")
    summary = DeterministicSummarizer().summarize(trace)
    ids = {e.event_id for e in trace.events}
    if not summary.claims or not all(
        c.event_ids and set(c.event_ids) <= ids for c in summary.claims
    ):
        raise SampleError("the offline summary of the copy cites events that do not exist")


def add_sample(
    run_dir: Path,
    samples_runs: Path,
    demonstrates: str,
    max_blob_bytes: int = MAX_BLOB_BYTES,
) -> Path:
    manifest = check_finished(run_dir)
    run_id = manifest["run_id"]
    dest = samples_runs / run_id
    if dest.exists():
        raise SampleError(f"{dest} already exists; samples are immutable, use a different run")
    hits = scan_for_secrets(run_dir)
    if hits:
        raise SampleError(
            "possible secrets found, nothing was copied. Check: " + ", ".join(hits[:10])
        )
    try:
        truncated = copy_run(run_dir, dest, max_blob_bytes)
        (dest / SIDECAR).write_text(
            json.dumps(
                {
                    "demonstrates": demonstrates,
                    "source": run_dir.name,
                    "truncated_blobs": truncated,
                },
                indent=2,
            )
            + "\n"
        )
        check_replayable(dest)
    except BaseException:
        shutil.rmtree(dest, ignore_errors=True)  # never leave half a sample behind
        raise
    write_index(samples_runs)
    return dest


def _row(run_dir: Path) -> dict[str, str]:
    def load(name: str) -> dict[str, Any]:
        path = run_dir / name
        return json.loads(path.read_text()) if path.exists() else {}

    manifest, status, side = load("manifest.json"), load("status.json"), load(SIDECAR)
    end = next(
        (e for e in reversed(read_trace(run_dir).events) if e.type == "run_end"),
        None,
    )
    steps = (end.totals or {}).get("steps", "") if end else ""
    model = (manifest.get("model") or {}).get("params", {}).get("model_id", "")
    harness = (manifest.get("harness") or {}).get("name", "")
    return {
        "run": run_dir.name,
        "task": str(manifest.get("task_instance_id", "")),
        "config": " / ".join(x for x in (model, harness) if x),
        "state": str(status.get("state", "")),
        "steps": str(steps),
        "demonstrates": str(side.get("demonstrates", "")),
    }


def write_index(samples_runs: Path) -> Path:
    """Rebuild ``samples/README.md`` (the index sits next to ``runs/``)."""
    rows = [_row(p) for p in sorted(samples_runs.iterdir()) if (p / "manifest.json").exists()]
    cols = ["run", "task", "config", "state", "steps", "demonstrates"]
    table = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    table += ["| " + " | ".join(r[c].replace("|", "/") for c in cols) + " |" for r in rows]
    body = "\n".join(table) if rows else "_No samples yet._"
    index = samples_runs.parent / "README.md"
    index.write_text(README_HEADER + body + "\n")
    return index


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Add a finished run to samples/runs/.")
    ap.add_argument("--run", type=Path, help="finished run folder (e.g. runs/<run_id>)")
    ap.add_argument("--demonstrates", default="", help="what this sample shows (one line)")
    ap.add_argument("--samples", type=Path, default=Path("samples/runs"))
    ap.add_argument("--max-blob-bytes", type=int, default=MAX_BLOB_BYTES)
    ap.add_argument("--reindex", action="store_true", help="only rebuild samples/README.md")
    args = ap.parse_args(argv)
    args.samples.mkdir(parents=True, exist_ok=True)
    try:
        if args.reindex:
            print(f"wrote {write_index(args.samples)}")
            return 0
        if not args.run:
            ap.error("--run is required (or use --reindex)")
        if not args.demonstrates.strip():
            ap.error("--demonstrates is required: say what this sample shows")
        dest = add_sample(args.run, args.samples, args.demonstrates.strip(), args.max_blob_bytes)
    except SampleError as why:
        print(f"not added: {why}", file=sys.stderr)
        return 1
    print(f"added {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
